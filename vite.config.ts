import { defineConfig, type Plugin } from 'vite'
import react from '@vitejs/plugin-react'
import { viteSingleFile } from 'vite-plugin-singlefile'
import path from 'node:path'
import { createHash } from 'node:crypto'

/**
 * Network first for the page itself (so an open app always gets the newest version when
 * online), cache first for hashed assets (they never change), everything precached so the
 * home-screen app opens offline. A new version waits until the page says "skip-waiting".
 */
function swSource(version: string, files: string[]) {
  return `// Rasoi service worker — generated by vite.config.ts, version ${version}
const CACHE = 'rasoi-${version}'
const FILES = ${JSON.stringify(files)}
self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)))
})
self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('rasoi-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  )
})
self.addEventListener('message', (e) => {
  if (e.data === 'skip-waiting') self.skipWaiting()
})
const timeout = (ms) => new Promise((_, reject) => setTimeout(() => reject(new Error('timeout')), ms))
self.addEventListener('fetch', (e) => {
  const req = e.request
  if (req.method !== 'GET') return
  const url = new URL(req.url)
  if (url.origin !== self.location.origin) return
  if (req.mode === 'navigate') {
    e.respondWith(
      Promise.race([fetch(req), timeout(4000)])
        .then((res) => {
          if (res.ok) caches.open(CACHE).then((c) => c.put('./', res.clone()))
          return res
        })
        .catch(() => caches.match('./', { ignoreSearch: true, ignoreVary: true }).then((r) => r || fetch(req))),
    )
    return
  }
  e.respondWith(
    caches.match(req, { ignoreSearch: true, ignoreVary: true }).then(
      (hit) =>
        hit ||
        fetch(req).then((res) => {
          if (res.ok && url.pathname.includes('/assets/')) {
            const copy = res.clone()
            caches.open(CACHE).then((c) => c.put(req, copy))
          }
          return res
        }),
    ),
  )
})
`
}

/**
 * Two targets:
 *  - `npm run build`        → dist/            normal web app (deploy anywhere, SPA fallback)
 *  - `npm run build:mobile` → dist-mobile/     one self-contained index.html (JS, CSS and fonts
 *                                               inlined) published as the claude.ai link you open on your phone
 */
export default defineConfig(({ mode }) => {
  const mobile = mode === 'artifact'

  // The hosted page pads itself for the phone's notch/home bar via env(), so
  // drop the host's extra top/bottom padding and the web-app-only tags.
  const mobileHtml: Plugin = {
    name: 'rasoi-mobile-html',
    transformIndexHtml: (html) =>
      html
        .replace(/\s*<link rel="manifest"[^>]*>/, '')
        .replace(/\s*<link rel="apple-touch-icon"[^>]*>/, '')
        .replace(/\s*<link rel="icon"[^>]*>/, '')
        .replace('</title>', '</title>\n    <style>:root{padding-top:0!important;padding-bottom:0!important}</style>'),
  }

  // The public site's service worker: keeps every built file for offline use and
  // makes each build a new version (the list of hashed file names changes).
  const serviceWorker: Plugin = {
    name: 'rasoi-service-worker',
    apply: 'build',
    generateBundle(_, bundle) {
      const files = Object.keys(bundle).filter((f) => !f.endsWith('.map') && f !== 'index.html')
      const statics = ['manifest.webmanifest', 'icon-192.png', 'icon-512.png', 'apple-touch-icon.png', 'favicon.svg']
      const version = createHash('sha256').update(files.sort().join('|')).digest('hex').slice(0, 12)
      this.emitFile({ type: 'asset', fileName: 'sw.js', source: swSource(version, ['./', ...statics, ...files]) })
    },
  }

  return {
    base: './',
    plugins: mobile ? [react(), mobileHtml, viteSingleFile()] : [react(), serviceWorker],
    resolve: { alias: { '@': path.resolve(__dirname, 'src') } },
    server: { host: true, port: 5173 },
    build: mobile
      ? { outDir: 'dist-mobile', assetsInlineLimit: 100_000_000, cssCodeSplit: false }
      : {
          rollupOptions: {
            output: {
              manualChunks: {
                react: ['react', 'react-dom', 'react-router-dom'],
                motion: ['framer-motion'],
                ui: ['vaul', 'lucide-react'],
              },
            },
          },
        },
  }
})
